import streamlit as st

st.set_page_config(
    page_title="FAQ | Loan Approval Demo",
    page_icon="❓",
    layout="wide",
)

st.title("Frequently Asked Questions")
st.caption("A quick guide to the Agentic AI Loan Approval Demo")

st.write(
    "This page explains the current proof of concept, how to interpret its "
    "outputs, and which capabilities are planned rather than implemented."
)

with st.expander("What does this demo do?", expanded=True):
    st.write(
        "It demonstrates a simplified loan assessment journey using fictional "
        "applicant records, Python rule-based checks, simulated document statuses, "
        "a preliminary recommendation, and human review."
    )

with st.expander("Does the demo approve or disburse real loans?"):
    st.write(
        "No. It is a learning and demonstration prototype. It does not make "
        "real lending decisions, sanction loans, or disburse funds."
    )

with st.expander("Is the data real?"):
    st.write(
        "No. The demo uses fictional applicant data. The records should not be "
        "treated as real customers or used to make real credit decisions."
    )

with st.expander("What does a preliminary recommendation mean?"):
    st.write(
        "It summarises the findings generated by the current assessment checks. "
        "It is not a final lending decision. An authorised credit officer must "
        "review the evidence and record the appropriate decision."
    )

with st.expander("Why might an application be flagged for further review?"):
    st.write(
        "A check may identify affordability concerns, missing or uncertain "
        "evidence, or another condition requiring attention. Review the displayed "
        "evidence, rule applied, and suggested next action before recording a decision."
    )

with st.expander("Are the document checks connected to real document or bureau APIs?"):
    st.write(
        "No. The current document statuses and mock credit information are "
        "simulated for demonstration. Live document extraction and credit bureau "
        "integrations have not been connected."
    )

with st.expander("Does the demo currently use autonomous LLM agents?"):
    st.write(
        "No. The current assessment uses Python rules and simulated checks. "
        "Specialised LLM-powered agents for document checks, policy lookup, "
        "credit assessment, and risk flagging are proposed future enhancements."
    )

with st.expander("Where is applicant data stored?"):
    st.write(
        "The current prototype stores applicant records in a MySQL database. "
        "A structured export is also available as lakehouse_applicants.csv."
    )

with st.expander("Is Google BigQuery connected?"):
    st.write(
        "No. BigQuery is not connected in the current implementation. It is a "
        "possible future cloud analytical layer, subject to access, security, "
        "and cost review."
    )

with st.expander("Can I export the applicant data?"):
    st.write(
        "The main application includes a CSV export workflow. The prepared "
        "lakehouse_applicants.csv file is also available in the project folder. "
        "Exports contain fictional demonstration data."
    )

with st.expander("Who makes the final decision?"):
    st.write(
        "The authorised human credit officer. Automated or rule-based findings "
        "are advisory and should be reviewed alongside the supporting evidence."
    )

with st.expander("How should this prototype be used responsibly?"):
    st.write(
        "Use it only with fictional or properly authorised data, protect database "
        "credentials, restrict access, and clearly distinguish simulated features "
        "from production integrations. Do not use this prototype to approve real loans."
    )

st.divider()
st.subheader("Need more information?")
st.write(
    "For this assignment demo, refer to the About, Solution Architecture, and "
    "Approach Story pages for project scope, current implementation, and proposed "
    "future enhancements."
)

st.caption(
    "Status note: MySQL, CSV, Streamlit, Python rule-based checks, simulated "
    "document statuses, and human decision recording are part of the current "
    "prototype. BigQuery, live external APIs, and LLM-powered agents are not connected."
)
